def test_documento_em_ingles(tmp_path):
    servico = ServicoDocumentos(PastaDocumentos(tmp_path), Tradutor(Idioma.EN_US), relogio=lambda: AGORA)
    texto = servico.salvar("solar energy", "It is renewable.").read_text()
    assert "*Generated by Robofael on 10/29/2026 at 10:15 AM.*" in texto and "**Request:** solar energy" in texto
