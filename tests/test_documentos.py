def test_documento_tem_titulo_data_pedido_e_conteudo(tmp_path):
    servico = ServicoDocumentos(PastaDocumentos(tmp_path), Tradutor(), relogio=lambda: AGORA)
    caminho = servico.salvar("energia solar", "Só um instante. A energia solar é renovável.\n\nE barata.")
