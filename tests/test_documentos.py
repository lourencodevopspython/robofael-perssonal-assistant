# ---------- Reconhecimento do pedido ----------
@pytest.mark.parametrize("fala, assunto", [
    ("gerar doc", None),
    ("Gerar doc.", None),
    ("gera um doc dessa resposta", None),
    ("gerar documento com a resposta", None),
    ("gerar doc disso", None),
    ("gerar dock da última resposta", None),  # como o reconhecimento de fala às vezes escreve
    ("generate a doc", None),
    ("make a document of the last answer", None),
    ("gerar doc sobre a história da aviação", "a história da aviação"),
    ("Gere um documento sobre energia solar no Brasil", "energia solar no Brasil"),
    ("gerar doc: dicas de produtividade", "dicas de produtividade"),
    ("faça um documento a respeito de reciclagem", "reciclagem"),
    ("por favor, gerar doc das minhas tarefas pendentes", "minhas tarefas pendentes"),
    ("generate a doc about the solar system", "the solar system"),
])
def test_reconhece_o_pedido_de_documento(fala, assunto):
    assert interpretar_pedido_documento(fala) == PedidoDocumento(assunto)


@pytest.mark.parametrize("fala", ["que horas são", "o documento do carro venceu", "abre o google docs",
                                  "anota tarefa gerar doc do projeto", "documentos"])
def test_outras_falas_nao_sao_pedido_de_documento(fala):
    assert interpretar_pedido_documento(fala) is None


def test_titulo_e_nome_do_arquivo():
    assert titulo_documento("  a história da aviação. ") == "A história da aviação"
    assert titulo_documento("palavra " * 30).endswith("…") and len(titulo_documento("palavra " * 30)) <= 81
    assert nome_arquivo("A história da aviação!", AGORA) == "2026-10-29 1015 - a-historia-da-aviacao"
    assert nome_arquivo("???", AGORA) == "2026-10-29 1015 - documento"


# ---------- Arquivo ----------
def test_grava_sem_sobrescrever(tmp_path):
    pasta = PastaDocumentos(tmp_path / "Documentos" / "Robofael")
    a = pasta.salvar("2026-10-29 1015 - teste", "um")
    b = pasta.salvar("2026-10-29 1015 - teste", "dois")
    assert (a.name, b.name) == ("2026-10-29 1015 - teste.md", "2026-10-29 1015 - teste (2).md")
    assert (a.read_text(), b.read_text()) == ("um", "dois")
    assert not list(a.parent.glob(".*.tmp"))  # sem temporários esquecidos


def test_pasta_padrao_segue_o_xdg_do_usuario(tmp_path):
    (tmp_path / ".config").mkdir()
    (tmp_path / ".config" / "user-dirs.dirs").write_text('XDG_DOCUMENTS_DIR="$HOME/Documentos"\n')
    assert pasta_documentos_padrao({"HOME": str(tmp_path)}) == tmp_path / "Documentos" / "Robofael"
    assert pasta_documentos_padrao({"HOME": str(tmp_path / "sem_xdg")}) == tmp_path / "sem_xdg" / "Documents" / \
        "Robofael"
    cfg = Configuracao.do_ambiente({"HOME": str(tmp_path), "ROBOFAEL_DOCUMENTOS": str(tmp_path / "meus")})
    assert cfg.pasta_documentos == tmp_path / "meus"


